/**
 * 練習曲データ
 *
 * 1 音ずつ「何の糸の、文化譜で何番」かを書いている。
 * n(糸, '文化譜の番号', 拍数, '歌詞', { 奏法・区切り })
 */
import { StringNo, Technique, Tuning, semitoneFromBunka } from './notation';

export interface SongNote {
  string: StringNo;
  semitone: number;
  beats: number;
  lyric?: string;
  section?: string;
  technique?: Technique;
}

export interface Song {
  id: string;
  title: string;
  subtitle: string;
  description: string;
  tuningId: Tuning['id'];
  honsu: number;
  bpm: number;
  difficulty: '入門' | '初級' | '中級';
  notes: SongNote[];
}

function n(
  string: StringNo,
  label: string,
  beats: number,
  lyric?: string,
  opts: { section?: string; technique?: Technique } = {}
): SongNote {
  const semitone = semitoneFromBunka(label);
  if (semitone === null) throw new Error(`文化譜の番号がまちがっています: ${label}`);
  return { string, semitone, beats, lyric, ...opts };
}

